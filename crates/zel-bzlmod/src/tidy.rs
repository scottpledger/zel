//! `bazel mod tidy`: fixes `use_repo` calls in the root module files according to the metadata
//! reported by module extensions (`extension_metadata()`), without requiring buildozer.
//! Mirrors `LockfileModuleExtensionMetadata.generateFixup` + buildozer's `use_repo_add/remove`.

use crate::model::*;
use crate::session::Session;
use std::collections::{BTreeMap, BTreeSet};

pub(crate) struct Fixup {
    /// module file (workspace-relative) -> commands (cmd, proxy name, repos)
    pub(crate) commands: Vec<(String, &'static str, String, Vec<String>)>,
    pub(crate) warning: String,
    pub(crate) success: String,
}

pub(crate) fn fixup_for(
    id_ext: &str,
    bzl_file: &str,
    usage: &ExtensionUsage,
    meta: Option<&crate::rt::ExtensionMetadata>,
    all_repos: &BTreeSet<String>,
) -> Result<Option<Fixup>, String> {
    let (deps, dev_deps): (Option<BTreeSet<String>>, Option<BTreeSet<String>>) = match meta.map(|m| m.use_all.as_str()) {
        Some("REGULAR") => (Some(all_repos.clone()), Some(BTreeSet::new())),
        Some("DEV") => (Some(BTreeSet::new()), Some(all_repos.clone())),
        Some(_) => {
            let m = meta.unwrap();
            for (what, l) in [("root_module_direct_deps", &m.explicit_root_direct_deps), ("root_module_direct_dev_deps", &m.explicit_root_direct_dev_deps)] {
                if let Some(l) = l {
                    let invalid: Vec<&String> = l.iter().filter(|r| !all_repos.contains(*r)).collect();
                    if !invalid.is_empty() {
                        return Err(format!(
                            "{what} contained the following repositories not generated by the extension: {}",
                            invalid.iter().map(|s| s.as_str()).collect::<Vec<_>>().join(", ")
                        ));
                    }
                }
            }
            if m.explicit_root_direct_deps.is_some() || m.explicit_root_direct_dev_deps.is_some() {
                (
                    m.explicit_root_direct_deps.clone().map(|v| v.into_iter().collect()),
                    m.explicit_root_direct_dev_deps.clone().map(|v| v.into_iter().collect()),
                )
            } else {
                let imports_of = |dev: bool| -> BTreeSet<String> {
                    usage.proxies.iter().filter(|p| p.dev_dependency == dev).flat_map(|p| p.imports.iter().map(|(_, e)| e.clone())).collect()
                };
                (
                    Some(imports_of(false).intersection(all_repos).cloned().collect()),
                    Some(imports_of(true).intersection(all_repos).cloned().collect()),
                )
            }
        }
        None => {
            let imports_of = |dev: bool| -> BTreeSet<String> {
                usage.proxies.iter().filter(|p| p.dev_dependency == dev).flat_map(|p| p.imports.iter().map(|(_, e)| e.clone())).collect()
            };
            (
                Some(imports_of(false).intersection(all_repos).cloned().collect()),
                Some(imports_of(true).intersection(all_repos).cloned().collect()),
            )
        }
    };
    let (Some(expected), Some(expected_dev)) = (deps, dev_deps) else { return Ok(None) };
    let has_non_dev = usage.proxies.iter().any(|p| !p.dev_dependency);
    let has_dev = usage.proxies.iter().any(|p| p.dev_dependency);
    if !has_non_dev && !expected.is_empty() {
        return Err("root_module_direct_deps must be empty if the root module contains no usages with dev_dependency = False".into());
    }
    if !has_dev && !expected_dev.is_empty() {
        return Err("root_module_direct_dev_deps must be empty if the root module contains no usages with dev_dependency = True".into());
    }
    let imports_of = |dev: bool| -> BTreeSet<String> {
        usage.proxies.iter().filter(|p| p.dev_dependency == dev).flat_map(|p| p.imports.iter().map(|(_, e)| e.clone())).collect()
    };
    let (actual, actual_dev) = (imports_of(false), imports_of(true));
    let add: BTreeSet<_> = expected.difference(&actual).cloned().collect();
    let remove: BTreeSet<_> = actual.difference(&expected).cloned().collect();
    let dev_add: BTreeSet<_> = expected_dev.difference(&actual_dev).cloned().collect();
    let dev_remove: BTreeSet<_> = actual_dev.difference(&expected_dev).cloned().collect();
    if add.is_empty() && remove.is_empty() && dev_add.is_empty() && dev_remove.is_empty() {
        return Ok(None);
    }
    let mut message = format!("The module extension {id_ext} defined in {bzl_file} reported incorrect imports of repositories via use_repo():\n\n");
    let all_actual: BTreeSet<_> = actual.union(&actual_dev).cloned().collect();
    let all_expected: BTreeSet<_> = expected.union(&expected_dev).cloned().collect();
    let join = |s: &BTreeSet<String>| s.iter().cloned().collect::<Vec<_>>().join(", ");
    let invalid: BTreeSet<_> = all_actual.difference(all_repos).cloned().collect();
    if !invalid.is_empty() {
        message += &format!("Imported, but not created by the extension (will cause the build to fail):\n    {}\n\n", join(&invalid));
    }
    let missing: BTreeSet<_> = all_expected.difference(&all_actual).cloned().collect();
    if !missing.is_empty() {
        message += &format!("Not imported, but reported as direct dependencies by the extension (may cause the build to fail):\n    {}\n\n", join(&missing));
    }
    let a: BTreeSet<_> = expected_dev.intersection(&actual).cloned().collect();
    if !a.is_empty() {
        message += &format!("Imported as a regular dependency, but reported as a dev dependency by the extension (may cause the build to fail when used by other modules):\n    {}\n\n", join(&a));
    }
    let b: BTreeSet<_> = expected.intersection(&actual_dev).cloned().collect();
    if !b.is_empty() {
        message += &format!("Imported as a dev dependency, but reported as a regular dependency by the extension (may cause the build to fail when used by other modules):\n    {}\n\n", join(&b));
    }
    let indirect: BTreeSet<_> = all_actual.intersection(all_repos).cloned().collect::<BTreeSet<_>>().difference(&all_expected).cloned().collect();
    if !indirect.is_empty() {
        message += &format!("Imported, but reported as indirect dependencies by the extension:\n    {}\n\n", join(&indirect));
    }
    message += "Fix the use_repo calls by running 'bazel mod tidy'.";
    let mut commands = vec![];
    if !add.is_empty() {
        let p = usage.proxies.iter().find(|p| !p.dev_dependency).unwrap();
        commands.push((p.containing_module_file.clone(), "use_repo_add", p.proxy_name.clone(), add.into_iter().collect()));
    }
    if !dev_add.is_empty() {
        let p = usage.proxies.iter().find(|p| p.dev_dependency).unwrap();
        commands.push((p.containing_module_file.clone(), "use_repo_add", p.proxy_name.clone(), dev_add.into_iter().collect()));
    }
    for p in &usage.proxies {
        let rm = if p.dev_dependency { &dev_remove } else { &remove };
        let to_remove: BTreeSet<String> = p.imports.iter().map(|(_, e)| e.clone()).filter(|e| rm.contains(e)).collect();
        if !to_remove.is_empty() {
            commands.push((p.containing_module_file.clone(), "use_repo_remove", p.proxy_name.clone(), to_remove.into_iter().collect()));
        }
    }
    let success = match &usage.isolation_key {
        Some((_, name)) => format!("Updated use_repo calls for isolated usage '{name}' of {}%{}", usage.bzl_file, usage.extension_name),
        None => format!("Updated use_repo calls for {}%{}", usage.bzl_file, usage.extension_name),
    };
    Ok(Some(Fixup {
        commands,
        warning: format!("{}: {message}", usage.proxies.first().map(|p| p.location.clone()).unwrap_or_default()),
        success,
    }))
}

/// Finds `use_repo(` calls whose first argument is `proxy`; returns (start, end) byte ranges.
fn find_use_repo_calls(src: &str, proxy: &str) -> Vec<(usize, usize)> {
    let mut out = vec![];
    let b = src.as_bytes();
    let mut i = 0;
    while let Some(p) = src[i..].find("use_repo(") {
        let start = i + p;
        // ensure it's a statement start (not part of identifier)
        if start > 0 && (b[start - 1].is_ascii_alphanumeric() || b[start - 1] == b'_') {
            i = start + 9;
            continue;
        }
        let mut depth = 0i32;
        let mut j = start + 8;
        let mut in_str: Option<u8> = None;
        let mut end = None;
        while j < b.len() {
            let c = b[j];
            if let Some(q) = in_str {
                if c == b'\\' {
                    j += 1;
                } else if c == q {
                    in_str = None;
                }
            } else if c == b'"' || c == b'\'' {
                in_str = Some(c);
            } else if c == b'#' {
                while j < b.len() && b[j] != b'\n' {
                    j += 1;
                }
                continue;
            } else if c == b'(' {
                depth += 1;
            } else if c == b')' {
                depth -= 1;
                if depth == 0 {
                    end = Some(j + 1);
                    break;
                }
            }
            j += 1;
        }
        let Some(end) = end else { break };
        let inner = &src[start + 9..end - 1];
        let first = inner.split(',').next().unwrap_or("").trim();
        if first == proxy {
            out.push((start, end));
        }
        i = end;
    }
    out
}

fn split_args(inner: &str) -> Vec<String> {
    let mut args = vec![];
    let mut cur = String::new();
    let mut in_str: Option<char> = None;
    let mut esc = false;
    let mut depth = 0;
    for c in inner.chars() {
        if let Some(q) = in_str {
            cur.push(c);
            if esc {
                esc = false;
            } else if c == '\\' {
                esc = true;
            } else if c == q {
                in_str = None;
            }
            continue;
        }
        match c {
            '"' | '\'' => {
                in_str = Some(c);
                cur.push(c);
            }
            '(' | '[' | '{' => {
                depth += 1;
                cur.push(c);
            }
            ')' | ']' | '}' => {
                depth -= 1;
                cur.push(c);
            }
            ',' if depth == 0 => {
                args.push(cur.trim().to_string());
                cur.clear();
            }
            _ => cur.push(c),
        }
    }
    if !cur.trim().is_empty() {
        args.push(cur.trim().to_string());
    }
    args.into_iter().filter(|a| !a.is_empty()).collect()
}

fn arg_repo_value(arg: &str) -> Option<String> {
    // "name" or key = "name", ignoring inline comments
    let clean = if let Some(i) = arg.find('#') { &arg[..i] } else { arg }.trim();
    let v = clean.rsplit('=').next().unwrap_or(clean).trim();
    if (v.starts_with('"') && v.ends_with('"') || v.starts_with('\'') && v.ends_with('\'')) && v.len() >= 2 {
        Some(v[1..v.len() - 1].to_string())
    } else {
        None
    }
}

fn render_call(args: &[String], multiline: bool) -> String {
    if multiline || args.iter().map(|a| a.len() + 2).sum::<usize>() > 60 {
        let mut s = String::from("use_repo(\n");
        for a in args {
            s.push_str(&format!("    {a},\n"));
        }
        s.push(')');
        s
    } else {
        format!("use_repo({})", args.join(", "))
    }
}

fn apply_command(src: &str, cmd: &str, proxy: &str, repos: &[String]) -> Result<String, String> {
    let proxy = if proxy.is_empty() { "_unnamed_usage" } else { proxy };
    let calls = find_use_repo_calls(src, proxy);
    let q = |r: &String| format!("\"{r}\"");
    match cmd {
        "use_repo_add" => {
            if let Some(&(s, e)) = calls.first() {
                let inner = &src[s + 9..e - 1];
                let multiline = inner.contains('\n');
                let mut args = split_args(inner);
                for r in repos {
                    if !args.iter().any(|a| arg_repo_value(a).as_deref() == Some(r.as_str()) && !a.contains('=')) {
                        args.push(q(r));
                    }
                }
                let mut new_src = String::new();
                new_src.push_str(&src[..s]);
                new_src.push_str(&render_call(&args, multiline));
                new_src.push_str(&src[e..]);
                Ok(new_src)
            } else {
                Err(format!("buildozer-style use_repo_add: no use_repo call found for '{proxy}'"))
            }
        }
        _ => {
            let mut out = src.to_string();
            for &(s, e) in calls.iter().rev() {
                let inner = &out[s + 9..e - 1];
                let multiline = inner.contains('\n');
                let args = split_args(inner);
                let kept: Vec<String> = args
                    .iter()
                    .enumerate()
                    .filter(|(i, a)| *i == 0 || !arg_repo_value(a).is_some_and(|v| repos.contains(&v)))
                    .map(|(_, a)| a.clone())
                    .collect();
                if kept.len() == 1 {
                    // Drop the (now empty) call including its trailing newline.
                    let mut end = e;
                    if out[end..].starts_with('\n') {
                        end += 1;
                    }
                    out.replace_range(s..end, "");
                } else {
                    out.replace_range(s..e, &render_call(&kept, multiline));
                }
            }
            Ok(out)
        }
    }
}

pub fn run_tidy(session: &Session) -> Result<String, (i32, String)> {
    let res = &session.resolution;
    let rt = &session.rt;
    let mut fixups: Vec<Fixup> = vec![];
    let mut errors: Vec<String> = vec![];
    for id in res.extension_ids() {
        if id.is_innate() {
            continue;
        }
        let Some((_, usage)) = res.usages_of(&id).into_iter().find(|(k, _)| k.is_root()) else { continue };
        let result = match rt.eval_extension_raw(&id) {
            Ok(r) => r,
            Err(e) => {
                errors.push(e);
                continue;
            }
        };
        let all: BTreeSet<String> = result.generated.iter().map(|(n, _)| n.clone()).collect();
        match fixup_for(&format!("{}", id.name), &id.bzl_file, usage, result.metadata.as_ref(), &all) {
            Ok(Some(f)) => fixups.push(f),
            Ok(None) => {}
            Err(e) => errors.push(e),
        }
    }
    let mut by_file: BTreeMap<String, String> = BTreeMap::new();
    let mut log = String::new();
    for f in &fixups {
        log.push_str(&format!("WARNING: {}\n", f.warning));
        for (file, cmd, proxy, repos) in &f.commands {
            let path = session.cfg.workspace.join(file);
            let cur = match by_file.get(file) {
                Some(s) => s.clone(),
                None => std::fs::read_to_string(&path).map_err(|e| (2, format!("Failed to read {}: {e}", path.display())))?,
            };
            let updated = apply_command(&cur, cmd, proxy, repos).map_err(|e| (2, e))?;
            by_file.insert(file.clone(), updated);
        }
    }
    for (file, content) in &by_file {
        let path = session.cfg.workspace.join(file);
        std::fs::write(&path, content).map_err(|e| (2, format!("Failed to write {}: {e}", path.display())))?;
    }
    for f in &fixups {
        log.push_str(&format!("INFO: {}\n", f.success));
    }
    if !errors.is_empty() {
        return Err((2, errors.join("\n")));
    }
    // Bazel reports fixups as events (stderr).
    for l in log.lines() {
        rt.info(l.to_string());
    }
    Ok(String::new())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn add_and_remove_use_repo() {
        let src = "ext = use_extension(\"//:e.bzl\", \"e\")\nuse_repo(ext, \"a\", \"b\")\n";
        let added = apply_command(src, "use_repo_add", "ext", &["c".into(), "a".into()]).unwrap();
        assert_eq!(added, "ext = use_extension(\"//:e.bzl\", \"e\")\nuse_repo(ext, \"a\", \"b\", \"c\")\n");
        let removed = apply_command(&added, "use_repo_remove", "ext", &["a".into(), "c".into()]).unwrap();
        assert_eq!(removed, "ext = use_extension(\"//:e.bzl\", \"e\")\nuse_repo(ext, \"b\")\n");
        let gone = apply_command(&removed, "use_repo_remove", "ext", &["b".into()]).unwrap();
        assert_eq!(gone, "ext = use_extension(\"//:e.bzl\", \"e\")\n");
        let multi = "use_repo(\n    ext,\n    \"a\",\n)\n";
        let m2 = apply_command(multi, "use_repo_add", "ext", &["z".into()]).unwrap();
        assert_eq!(m2, "use_repo(\n    ext,\n    \"a\",\n    \"z\",\n)\n");
        let kw = "use_repo(ext, x = \"a\", \"b\")";
        assert_eq!(apply_command(kw, "use_repo_remove", "ext", &["a".into()]).unwrap(), "use_repo(ext, \"b\")");

        let with_comments = "use_repo(\n    ext,\n    \"a\", # inline comment\n    \"b\",\n)\n";
        let rm_comment = apply_command(with_comments, "use_repo_remove", "ext", &["a".into()]).unwrap();
        assert_eq!(rm_comment, "use_repo(\n    ext,\n    # inline comment\n    \"b\",\n)\n");
    }

    #[test]
    fn test_tidy_removes_invalid_use_repo() {
        use crate::commands::run_bzlmod_command;
        crate::resolve::HERMETIC_BAZEL_TOOLS.with(|h| h.set(true));

        let temp = std::env::temp_dir().join(format!("tidy_test_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&temp);
        std::fs::create_dir_all(&temp).unwrap();
        let ws = temp.join("ws");
        let ob = temp.join("ob");
        std::fs::create_dir_all(&ws).unwrap();

        std::fs::write(
            ws.join("ext.bzl"),
            r#"
def _repo_impl(ctx):
    ctx.file("BUILD", "")
r = repository_rule(implementation = _repo_impl)

def _ext_impl(ctx):
    r(name = "valid_repo")
ext = module_extension(implementation = _ext_impl)
"#,
        ).unwrap();

        std::fs::write(
            ws.join("MODULE.bazel"),
            r#"
module(name = "root")
ext = use_extension("//:ext.bzl", "ext")
use_repo(ext, "valid_repo", "invalid_unused")
"#,
        ).unwrap();

        let a = vec![
            "--registry=file:///nonexistent-registry".to_string(),
            "--check_direct_dependencies=off".into(),
            "tidy".to_string(),
        ];
        let out = run_bzlmod_command("mod", &a, &ws, &ob);
        assert_eq!(out.exit_code, 0, "mod tidy must succeed: {}", out.stderr);

        let module_content = std::fs::read_to_string(ws.join("MODULE.bazel")).unwrap();
        assert!(
            !module_content.contains("invalid_unused"),
            "MODULE.bazel must have invalid_unused removed: {module_content}"
        );
        assert!(
            module_content.contains("valid_repo"),
            "MODULE.bazel must retain valid_repo: {module_content}"
        );
    }
}
