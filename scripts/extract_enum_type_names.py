#!/usr/bin/env python3
"""Generates crates/zel-options/src/enum_type_names.rs from the Bazel Java sources.

`EnumConverter.convert` reports `Not a valid <typeName>: '<input>' (should be <values>)` where `typeName` is the
second argument of the converter's `super(Enum.class, "<typeName>")` call.  For every `@Option(converter = X.class)`
whose converter is an `EnumConverter`/`BoolOrEnumConverter` subclass this script resolves the type name and emits
`(flag, converter simple name, type name)` rows.

Usage: extract_enum_type_names.py [--bazel-dir DIR] [--out FILE | --check]
"""
