#!/usr/bin/env python3
"""Regenerates the corpus-derived unit tests in crates/zel-starlark/src/syntax/bazel_syntax_corpus_tests.rs
from the cached real-bazel results (only snippets whose bazel errors are pure scanner/parser errors)."""
import os, re, glob
W = os.environ.get("WORK", "/tmp/qh5p")
D = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(D, "../../../crates/zel-starlark/src/syntax/bazel_syntax_corpus_tests.rs")
PARSE_ONLY = ["syntax error", "invalid character", "unclosed string", "indentation error", "not supported",
    "Tab characters", "invalid escape", "invalid hex", "invalid binary", "invalid octal", "invalid float",
    "invalid base", "Trailing comma", "Implicit string", "missing else", "not associative", "keyword argument must",
    "expected an indented", "octal escape", "floating-point", "Starlark does not"]
def rs(s):
    o = ['"']
    for ch in s:
        if ch == '"': o.append('\\"')
        elif ch == '\\': o.append('\\\\')
        elif ch == '\n': o.append('\\n')
        elif ch == '\r': o.append('\\r')
        elif ch == '\t': o.append('\\t')
        elif ord(ch) < 32 or ord(ch) >= 127: o.append('\\u{%x}' % ord(ch))
        else: o.append(ch)
    o.append('"')
    return ''.join(o)
cases = []
for f in sorted(glob.glob(D + "/s*.txt")):
    n = os.path.basename(f)[:-4]
    c = W + "/bcache/" + n + ".cmp"
    if not os.path.exists(c): continue
    txt = open(c, encoding="latin-1").read()
    err = txt.split("--err\n", 1)[1]
    exp = []
    ok = True
    for line in err.splitlines():
        m = re.match(r"ERROR: <WS>/e/BUILD:(\d+):(\d+): (.*)$", line)
        if m:
            if not any(m.group(3).startswith(p) or p in m.group(3) for p in PARSE_ONLY): ok = False
            exp.append((int(m.group(1)), int(m.group(2)), m.group(3)))
    if not exp or not ok: continue
    src = open(f, "rb").read().decode("latin-1")
    cases.append((n, src, exp))
with open(OUT, "w", encoding="utf-8") as o:
    o.write("// Generated by scripts/query_harness/syntax/gen_unit_tests.py from real Bazel 9.3.2 output.\n")
    o.write("// Do not edit by hand.\n\n")
    o.write("use super::bazel_syntax::parse_errors;\n\n")
    o.write("type Case = (&'static str, &'static str, &'static [(usize, usize, &'static str)]);\n\n")
    o.write("const CASES: &[Case] = &[\n")
    for n, src, exp in cases:
        # `src` is Latin-1 text; the Rust str holds the same bytes as UTF-8 text of those chars
        # only for ASCII, so feed non-ASCII as raw bytes decoded back from latin-1 -> utf-8.
        o.write("    (%s, %s, &[%s]),\n" % (rs(n), rs(src), ", ".join("(%d, %d, %s)" % (a, b, rs(m)) for a, b, m in exp)))
    o.write("];\n\n")
    o.write('''#[test]
fn corpus_matches_bazel() {
    let mut failures = Vec::new();
    for (name, src, expected) in CASES {
        // The snippet is stored as Latin-1 chars; `parse_errors` maps bytes to chars, so convert
        // the chars back to the original UTF-8 byte sequence first.
        let bytes: Vec<u8> = src.chars().map(|c| c as u32 as u8).collect();
        let text = String::from_utf8(bytes).unwrap();
        let got: Vec<(usize, usize, String)> = parse_errors("BUILD", &text)
            .into_iter()
            .map(|e| (e.line, e.column, e.message))
            .collect();
        let want: Vec<(usize, usize, String)> =
            expected.iter().map(|&(l, c, m)| (l, c, m.to_string())).collect();
        if got != want {
            failures.push(format!("{name}: {src:?}\\n  want {want:?}\\n  got  {got:?}"));
        }
    }
    assert!(failures.is_empty(), "{} mismatches:\\n{}", failures.len(), failures.join("\\n"));
}
''')
print(len(cases), "cases ->", OUT)
